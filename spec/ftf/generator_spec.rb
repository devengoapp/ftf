# frozen_string_literal: true

require "json"
require "tmpdir"

RSpec.describe FTF::Generator do
  def fixture(name)
    File.binread(File.expand_path("../fixtures/#{name}", __dir__))
  end

  def report(name)
    JSON.parse(fixture("#{name}.json"), symbolize_names: true)
  end

  # Returns { filename => bytes } for the files generate! writes.
  def generate(data)
    Dir.mktmpdir do |dir|
      Dir.chdir(dir) { described_class.new(data).generate! }
      Dir.children(dir).to_h { |name| [name, File.binread(File.join(dir, name))] }
    end
  end

  def records(name)
    generate(fixture("#{name}.json")).values.first.split("\n")
  end

  # Records with an action letter after the type carry the index one byte later.
  def record_index(record)
    offset = %w[10 20 30].include?(record[0, 2]) ? 12 : 11
    record[offset, 10].to_i
  end

  describe "#generate!" do
    {
      "negative" => "FTF_A00000000_202610_001.txt",
      "monthly" => "FTF_A00000000_202610_002.txt",
      "complementary" => "FTF_A00000000_202609_001.txt"
    }.each do |name, filename|
      # The reference files were generated by ftf 0.0.9.
      it "writes the #{name} file byte for byte as before" do
        expect(generate(fixture("#{name}.json"))).to eq(filename => fixture("#{name}.txt"))
      end
    end

    it "accepts a symbol-keyed hash as well as a JSON string" do
      expect(generate(report("monthly"))).to eq(generate(fixture("monthly.json")))
    end

    it "nests records as header, product blocks and footer" do
      expect(records("monthly").map { |record| record[0, 2] })
        .to eq(%w[00 10 20 30 20 30 30 19 10 20 30 19 99])
    end

    it "makes every record 250 bytes long" do
      %w[negative monthly complementary].each do |name|
        expect(records(name).map(&:bytesize).uniq).to eq([250]), name
      end
    end

    it "numbers records consecutively from 1" do
      lines = records("monthly")
      expect(lines.map { |record| record_index(record) }).to eq((1..lines.size).to_a)
    end

    it "counts products and records in the footer" do
      footer = records("monthly").last
      expect([footer[21, 10], footer[31, 10]]).to eq(%w[0000000002 0000000013])
    end

    it "encodes names in ISO-8859-1" do
      holder = records("monthly").find { |record| record.start_with?("20") }
      expect(holder.byteslice(22, 18)).to eq("Muñoz Peña, Begoña".encode(Encoding::ISO_8859_1).b)
    end
  end

  describe "validation" do
    def build(name, **changes)
      described_class.new(report(name).merge(changes))
    end

    it "requires a complementary file for a request id" do
      expect { build("monthly", request_id: "REQ000000000001") }
        .to raise_error(RuntimeError, /request id must be complementary/)
    end

    it "requires a negative file without products" do
      expect { build("negative", file_type: "M") }
        .to raise_error(RuntimeError, /without product records must be negative/)
    end

    it "requires a monthly or complementary file with products" do
      expect { build("monthly", file_type: "N") }
        .to raise_error(RuntimeError, /must be monthly or complementary/)
    end

    it "requires a fiscal id" do
      expect { build("negative", fiscal_id: "") }.to raise_error(RuntimeError, /fiscal_id/)
    end

    it "requires a period" do
      expect { build("negative", period: nil) }.to raise_error(RuntimeError, /period/)
    end

    it "rejects data that is neither a JSON string nor a hash" do
      expect { described_class.new([]) }.to raise_error(RuntimeError, /JSON string/)
    end
  end
end
